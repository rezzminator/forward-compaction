/**
 * The forward handoff the party holds, with the message it is in: the newest text a record of this party holds
 * (`recorded`), else the one leading the context, where an install puts it. A text opening like one anywhere else
 * is a person's message. Undefined when there is none.
 */
export function heldForward(msgs: readonly ApiMsg[], recorded?: (text: string) => boolean): { text: string; index: number; recorded: boolean } | undefined {
  const firstAnswer = msgs.findIndex((m) => m.role === 'assistant');
  const leadEnd = firstAnswer < 0 ? msgs.length : firstAnswer;
  let leading: { text: string; index: number; recorded: boolean } | undefined;
  for (let i = msgs.length - 1; i >= 0; i--) {
    const m = msgs[i]!;
    if (m.role !== 'user') continue;
    for (const b of blocksOf(m)) {
      if (b.type !== 'text' || !textOf(b).startsWith(FORWARD_OPENING)) continue;
      if (recorded?.(textOf(b))) return { text: textOf(b), index: i, recorded: true };
      if (i < leadEnd && leading === undefined) leading = { text: textOf(b), index: i, recorded: false };
    }
  }
  return leading;
}

/**
 * The user entries of a transcript before its last compaction, from `grep -n` lines of the JSONL file, as messages
 * userMessages reads: Claude Code's own summary replaced them in the context, the file still holds them. A command's
 * or skill's expansion (isMeta) and a summary are left out; each entry stands alone, so none reads as another's expansion.
 */
export function priorPrompts(grepLines: string, boundaryLine: number, afterWakeSeq?: number): ApiMsg[] {
  const out: ApiMsg[] = [];
  // A saved handoff may never have installed. If its wake is absent, retain
  // the transcript rather than silently treating every prompt as already carried.
  for (const line of grepLines.split('\n')) {
    const m = /^(\d+):([\s\S]*)$/.exec(line);
    if (m === null || Number(m[1]) >= boundaryLine) continue;
    let entry: { type?: unknown; isMeta?: unknown; isCompactSummary?: unknown; message?: { role?: unknown; content?: unknown }; attachment?: { type?: unknown }; rendered?: unknown };
    try {
      entry = JSON.parse(m[2]!);
    } catch {
      continue;
    }
    const c = entry.message?.content;
    const text = typeof c === 'string' ? c : Array.isArray(c) ? c.filter((b) => b !== null && typeof b === 'object' && (b as Block).type === 'text').map((b) => textOf(b as Block)).join('\n') : '';
    if (entry.type === 'user' && afterWakeSeq !== undefined && text.startsWith(`${FORWARD_OPENING} ${afterWakeSeq}:`)) { out.length = 0; continue; }
    // A message that reached the party mid-turn is an attachment the harness rendered as a reminder; userMessages reads it.
    if (entry.type === 'attachment' && entry.attachment?.type === 'queued_command') {
      const rendered = Array.isArray(entry.rendered) ? entry.rendered.map((r) => (r !== null && typeof r === 'object' && typeof (r as { content?: unknown }).content === 'string' ? (r as { content: string }).content : '')).join('\n') : '';
      if (rendered.trim() === '') continue;
      out.push({ role: 'user', content: [{ type: 'text', text: rendered }] });
      out.push({ role: 'assistant', content: [] });
      continue;
    }
    if (entry.type !== 'user' || entry.isCompactSummary === true || entry.message === undefined) continue;
    const content = entry.message.content;
    if (typeof content !== 'string' && !Array.isArray(content)) continue;
    // An expansion is meta; so is a mid-turn message in its plain form, which is the parent's or the person's words.
    if (entry.isMeta === true && !QUEUED_HEADS.some((head) => (typeof content === 'string' ? content : content.map((b) => (b !== null && typeof b === 'object' && typeof (b as Block).text === 'string' ? (b as Block).text : '')).join('')).trimStart().startsWith(head))) continue;
    out.push({ role: 'user', content: content as ApiMsg['content'] });
    out.push({ role: 'assistant', content: [] });
  }
  return out;
}

/**
 * The model's tool calls before a transcript's last compaction, from `grep -n` lines of the JSONL file, as messages
 * fileTrail reads: Claude Code's own summary replaced them in the context, the file still holds them.
 */
export function priorCalls(grepLines: string, boundaryLine: number): ApiMsg[] {
  const out: ApiMsg[] = [];
  for (const line of grepLines.split('\n')) {
    const m = /^(\d+):([\s\S]*)$/.exec(line);
    if (m === null || Number(m[1]) >= boundaryLine) continue;
    let entry: { type?: unknown; message?: { content?: unknown } };
    try {
      entry = JSON.parse(m[2]!);
    } catch {
      continue;
    }
    const content = entry.message?.content;
    if (entry.type !== 'assistant' || !Array.isArray(content)) continue;
    out.push({ role: 'assistant', content: content as ApiMsg['content'] });
  }
  return out;
}

/**
 * Two trails as one, at most `max`: the newer one's files first, then the older one's it lacks. A file the older trail
 * created stays created; one touched in both is edited unless both only read it.
 */
export function mergeTrail(older: readonly TrailEntry[] | undefined, newer: readonly TrailEntry[], max: number): TrailEntry[] {
  const before = new Map((older ?? []).map((t) => [t.path, t.tag] as const));
  const merged = newer.map((t): TrailEntry => {
    const old = before.get(t.path);
    if (old === undefined) return t;
    return { tag: old === 'C' ? 'C' : old === 'R' && t.tag === 'R' ? 'R' : 'E', path: t.path };
  });
  for (const t of older ?? []) if (!newer.some((n) => n.path === t.path)) merged.push(t);
  return merged.slice(0, max);
}

/** Why a trail file was not outlined: gone, not a file, past the byte cap, or a read that failed. */
export type TrailMiss = { path: string; why: 'missing' | 'not-file' | 'too-large' | 'unreadable'; problem: string };

/**
 * The trail after its files were read for outlines. A path that is no file (a directory a `cp` or `mv` wrote into)
 * leaves it at once: no file tag. A path gone from disk is shown this once, with its note, and left out of the trail
 * the record carries, so no later handoff re-reads or re-tells it. A file past the cap stays, without an outline. Each
 * of these is a note, logged at info; only a read that failed is a problem, logged as one.
 */
export function settleTrail(trail: readonly TrailEntry[], misses: readonly TrailMiss[], cwd: string): { shown: TrailEntry[]; carried: TrailEntry[]; notes: string[]; problems: string[] } {
  const notFile = new Set(misses.filter((m) => m.why === 'not-file').map((m) => m.path));
  const missing = new Set(misses.filter((m) => m.why === 'missing').map((m) => m.path));
  const notes: string[] = [];
  const problems: string[] = [];
  for (const m of misses) {
    if (m.why === 'missing') notes.push(`outline ${m.path}: not found; check the prior file-tool path (absolute or relative to session cwd ${cwd}); the file may have moved or been deleted, so later handoffs leave it out`);
    else if (m.why === 'not-file') notes.push(`outline ${m.path}: ${m.problem}, so it leaves the file trail`);
    else if (m.why === 'too-large') notes.push(`outline ${m.path}: ${m.problem}, so it stays in the trail without an outline`);
    else problems.push(`outline ${m.path}: ${m.problem}`);
  }
  const shown = trail.filter((t) => !notFile.has(t.path));
  return { shown, carried: shown.filter((t) => !missing.has(t.path)), notes, problems };
}

/** The calls a model makes to reach the forward handoff itself: they do no work on a request. */
const reachesHandoff = (name: unknown): boolean => name === 'ToolSearch' || (typeof name === 'string' && name.endsWith(FORWARD_TOOL));

/**
 * Whether the forward handoff call is the reply to the latest prompt: after it the model did nothing but reach for the
 * handoff. A nudged handoff comes after work on the prompt, so it is not one.
 */
export function handoffInReply(msgs: readonly ApiMsg[], opts: CarryOptions = {}): boolean {
  let worked = -1;
  for (let i = msgs.length - 1; i >= 0 && worked < 0; i--) {
    const m = msgs[i]!;
    if (m.role === 'assistant' && blocksOf(m).some((b) => b.type === 'tool_use' && !reachesHandoff(b.name))) worked = i;
  }
  // A message that reached the party mid-turn is answered by the work it orders, not by a handoff, unless it asks for one.
  return userEntries(msgs.slice(worked + 1), opts).some((e) => !e.queued || askedToCompact([e.text]));
}

/**
 * Whether text reached the person after the newest message a person wrote in `msgs` (a notice is none): answered once a turn ended on text,
 * partially answered when text came mid-turn, unanswered when none came. The text beside the handoff call is no reply.
 * With no user message (`found` false), the same verdict on all of `msgs`, for a message an earlier handoff carried.
 */
export function replyAfter(msgs: readonly ApiMsg[], opts: CarryOptions = {}): { status: ReplyStatus; found: boolean; latest?: string } {
  const latest = userEntries(msgs, opts).filter((e) => !NOTICE.test(e.text)).at(-1);
  let status: ReplyStatus = 'unanswered';
  for (const [i, m] of msgs.entries()) {
    if (m.role !== 'assistant' || (latest !== undefined && i <= latest.at)) continue;
    const blocks = blocksOf(m);
    if (blocks.some((b) => b.type === 'tool_use' && reachesHandoff(b.name)) || !blocks.some((b) => b.type === 'text' && textOf(b).trim() !== '')) continue;
    // A response without a tool call ends the turn: its text is the reply.
    status = blocks.some((b) => b.type === 'tool_use') ? (status === 'answered' ? status : 'partially answered') : 'answered';
  }
  return { status, found: latest !== undefined, ...(latest !== undefined ? { latest: latest.text } : {}) };
}

/**
 * Whether the context opens with Claude Code's own summary: the prompts before it are then only in the transcript file.
 * The reminders Claude Code re-sends after a compaction (CLAUDE.md, session context, date) come before it.
 */
export function opensWithSummary(msgs: readonly ApiMsg[]): boolean {
  return openingSummary(msgs) !== undefined;
}

/** Claude Code's own summary when the context opens with it (past the reminders it puts first), else undefined. */
export function openingSummary(msgs: readonly ApiMsg[]): string | undefined {
  for (const m of msgs) {
    if (m.role !== 'user') return undefined;
    for (const b of blocksOf(m)) {
      if (b.type !== 'text' || textOf(b).trimStart().startsWith('<system-reminder>')) continue;
      return textOf(b).startsWith(SUMMARY_OPENING) ? textOf(b) : undefined;
    }
  }
  return undefined;
}

/** The sections of Claude Code's summary that hold what it knew; the request, prompts, tasks, current work and next step are carried newer elsewhere. */
const KNOWLEDGE = new Set(['Key Technical Concepts', 'Files and Code Sections', 'Errors and fixes', 'Problem Solving']);
const SECTION = /^\d+\.\s+(.+?):\s*$/;
const CLOSING = /^(?:If you need specific details from before compaction|Continue the conversation from where it left off|The messages after this summary are)/;

/** What Claude Code's summary knew, as `Section:` then its lines, dedented, blank lines dropped; undefined when it has none of those sections. */
export function summaryKnowledge(summary: string): string | undefined {
  const out: string[] = [];
  let keep = false;
  for (const line of summary.replace(/\r\n?/g, '\n').split('\n')) {
    if (CLOSING.test(line)) break;
    const head = SECTION.exec(line);
    if (head !== null) {
      keep = KNOWLEDGE.has(head[1]!.trim());
      if (keep) out.push(`${head[1]!.trim()}:`);
      continue;
    }
    if (keep && line.trim() !== '') out.push(line.replace(/^ {1,3}/, '').trimEnd());
  }
  return out.length > 0 ? out.join('\n') : undefined;
}

/** The longest outline line, and the per-language patterns whose first non-empty group names a symbol. */
export const OUTLINE_LINE_MAX = 400;
/** A file larger than this is named without an outline: reading it whole at every handoff costs more than its names give. */
export const OUTLINE_FILE_MAX_BYTES = 1024 * 1024;
const TS = [/^export\s+(?:default\s+)?(?:declare\s+)?(?:abstract\s+)?(?:async\s+)?(?:function\*?|const|let|var|class|type|interface|enum)\s+([A-Za-z_$][\w$]*)/, /^(?:async\s+)?function\*?\s+([A-Za-z_$][\w$]*)/, /^(?:abstract\s+)?(?:class|interface|type|enum)\s+([A-Za-z_$][\w$]*)/];
const TESTS = [/^\s*(?:describe|it|test)(?:\.\w+)?\(\s*(['"`])(.+?)\1/];
const OUTLINE_RULES: [RegExp, RegExp[]][] = [
  [/\.(?:test|spec)\.[cm]?[jt]sx?$/, [...TESTS, ...TS]],
  [/\.[cm]?[jt]sx?$/, TS],
  [/\.go$/, [/^func\s+\(\s*\w*\s*\*?(\w+)[^)]*\)\s*(\w+)/, /^func\s+(\w+)/, /^type\s+(\w+)/]],
  [/\.pyi?$/, [/^(?:async\s+)?def\s+(\w+)/, /^class\s+(\w+)/]],
  [/\.rs$/, [/^(?:pub(?:\([^)]*\))?\s+)?(?:async\s+)?(?:fn|struct|enum|trait|type|mod)\s+(\w+)/]],
  [/(?:\.(?:sh|bash|zsh)|\/[^/.]+)$/, [/^(?:function\s+)?([\w-]+)\s*\(\)\s*\{/, /^function\s+([\w-]+)\s*\{/]],
  [/\.(?:md|mdx|markdown)$/, [/^#{1,3}\s+(.+?)\s*#*$/]],
  [/\.ya?ml$/, [/^([\w.-]+):/]],
  [/\.toml$/, [/^\[\[?([^\]]+)\]/]],
];

/**
 * What a file defines, as one line: its line count, then the names it declares at top level, in order and once each —
 * exports, functions, types and classes; Go methods as `Type.Name`; test names; Markdown headings to depth 3; top-level
 * keys of JSON, YAML and TOML. A file of no known kind, or one whose names cannot be read, gives its line count alone.
 */
export function outline(path: string, text: string, max = OUTLINE_LINE_MAX): string {
  const lines = text.replace(/\r\n?/g, '\n').split('\n');
  if (lines.at(-1) === '') lines.pop();
  const names: string[] = [];
  const add = (name: string): void => {
    const one = name.trim();
    if (one !== '' && !names.includes(one)) names.push(one);
  };
  if (/\.json$/.test(path)) {
    try {
      const parsed: unknown = JSON.parse(text);
      if (parsed !== null && typeof parsed === 'object' && !Array.isArray(parsed)) Object.keys(parsed).forEach(add);
    } catch {
      // Not JSON as it stands: the line count alone says the file is there.
    }
  } else {
    const rules = OUTLINE_RULES.find(([kind]) => kind.test(path))?.[1] ?? [];
    const markdown = /\.(?:md|mdx|markdown)$/.test(path);
    let fenced = false;
    for (const line of lines) {
      if (markdown && /^\s*(?:```|~~~)/.test(line)) fenced = !fenced;
      if (fenced) continue;
      for (const rule of rules) {
        const m = rule.exec(line);
        if (m === null) continue;
        const groups = m.slice(1).filter((g): g is string => g !== undefined && g !== '' && !/^['"`]$/.test(g));
        add(groups.length === 2 && rule.source.startsWith('^func') ? `${groups[0]}.${groups[1]}` : (groups[0] ?? ''));
        break;
      }
    }
  }
  const head = `${lines.length} lines`;
  if (names.length === 0) return head;
  let body = `${head}: ${names[0]}`;
  for (let n = 1; n < names.length; n++) {
    const more = `, +${names.length - n} more`;
    const next = `${body}, ${names[n]}`;
    const last = n === names.length - 1;
    if ((last ? next.length : next.length + `, +${names.length - n - 1} more`.length) > max) return `${body}${more}`;
    body = next;
  }
  return body;
}

/**
 * The skills and commands a handoff carries: those the earlier wake carried, oldest first, then those invoked since in
 * last-use order (an invoked one moves after the carried and wins, so its newest directory is kept), once each, minus
 * the names `drop_skills` lists.
 */
export function chainSkills(carried: readonly Invocation[] | undefined, invoked: readonly Invocation[], dropped: readonly string[], policy: SkillPolicy = DEFAULT_SKILL_POLICY): Invocation[] {
  const fresh = new Set(invoked.map((x) => x.name));
  const gone = new Set([...dropped, ...policy.dropSkills]);
  return [...(carried ?? []).filter((x) => !fresh.has(x.name)), ...invoked].filter((x) => policy.pinSkills.includes(x.name) || !gone.has(x.name));
}

/** Queue events and rendered attachments missing from the messages API, after the last installed wake. */
export function queuedPrompts(grepLines: string, { parent = [], afterLine = 0, wake }: { parent?: readonly string[]; afterLine?: number; wake?: string } = {}): { users: string[]; through: number; afterWake: boolean; order?: string[]; delivered?: string[]; skipped?: string[] } {
  /** The lines that could not be read, each named: one bad line never costs the others. */
  const skipped: string[] = [];
  const queued: { text: string; delivered: boolean; line: number; deliveryLine?: number }[] = [];
  const typed: { text: string; line: number }[] = [];
  let through = afterLine;
  let cutoff = afterLine;
  let afterWake = false;
  for (const line of grepLines.split('\n')) {
    const match = /^(\d+):([\s\S]*)$/.exec(line);
    if (match === null) continue;
    const at = Number(match[1]);
    let entry: Record<string, any>;
    try { entry = JSON.parse(match[2]!); } catch { skipped.push(`line ${match[1]} (invalid JSON)`); continue; }
    if (entry === null || typeof entry !== 'object' || Array.isArray(entry)) { skipped.push(`line ${match[1]} (not an object)`); continue; }
    through = Math.max(through, at);
    if (entry.type === 'user') {
      const c = entry.message?.content;
      const texts = typeof c === 'string' ? [c] : Array.isArray(c) ? c.filter((b: Block) => b !== null && typeof b === 'object' && b.type === 'text').map((b: Block) => textOf(b)) : [];
      if (texts.some((t: string) => t.startsWith(FORWARD_OPENING))) {
        if (at > afterLine && wake !== undefined && texts.some((t: string) => t.startsWith(wake))) { cutoff = at; afterWake = true; }
      } else if (entry.isMeta !== true && entry.isCompactSummary !== true && (typeof c === 'string' || Array.isArray(c))) {
        for (const text of userMessages([{ role: 'user', content: c }], { parent })) typed.push({ text, line: at });
      }
    } else if (entry.type === 'queue-operation' && entry.operation === 'enqueue' && typeof entry.content === 'string') {
      queued.push({ text: collapseWhitespace(entry.content), delivered: false, line: at });
    } else if (entry.type === 'attachment' && entry.attachment?.type === 'queued_command') {
      const rendered = Array.isArray(entry.rendered) ? entry.rendered.map((r: unknown) => r !== null && typeof r === 'object' && typeof (r as { content?: unknown }).content === 'string' ? (r as { content: string }).content : '').join('\n') : '';
      const said = takeQueued(rendered, parent).messages;
      if (said.length === 0 && entry.attachment.origin?.kind === 'human' && typeof entry.attachment.prompt === 'string') said.push(entry.attachment.prompt);
      for (const text of said.map(collapseWhitespace)) {
        // Scan the prefix too: a late attachment acknowledges its original enqueue,
        // even when that enqueue was already carried before the saved cursor/wake.
        const pending = queued.find((q) => q.text === text && !q.delivered);
        if (pending !== undefined) { pending.delivered = true; pending.deliveryLine = at; }
        else queued.push({ text, delivered: true, line: at });
      }
    }
  }
  const fresh = queued.filter((q) => q.line > cutoff && q.text !== '');
  const ordinary = typed.filter((q) => q.line > cutoff);
  const order = [...fresh, ...ordinary].sort((a, b) => a.line - b.line).map((q) => q.text);
  const delivered = queued.filter((q) => q.line <= cutoff && (q.deliveryLine ?? 0) > cutoff).map((q) => q.text);
  return { users: fresh.map((q) => q.text), through, afterWake, ...(ordinary.length > 0 ? { order } : {}), ...(delivered.length > 0 ? { delivered } : {}), ...(skipped.length > 0 ? { skipped } : {}) };
}

/** Match queue entries to API deliveries by occurrence; a carried cursor makes older identical prompts independent. */
export function mergeQueuedUsers(previous: readonly string[], fresh: readonly string[], queued: readonly string[], afterCursor = false, order: readonly string[] = []): string[] {
  const seen = new Map<string, number>();
  for (const user of [...(afterCursor ? [] : previous), ...fresh]) {
    const text = collapseWhitespace(user);
    seen.set(text, (seen.get(text) ?? 0) + 1);
  }
  const unseen = queued.filter((user) => {
    const text = collapseWhitespace(user);
    const count = seen.get(text) ?? 0;
    if (count === 0) return true;
    seen.set(text, count - 1);
    return false;
  });
  const merged = [...fresh, ...unseen];
  if (order.length === 0) return merged;
  const positions = new Map<string, number[]>();
  order.forEach((text, index) => {
    const key = collapseWhitespace(text);
    positions.set(key, [...(positions.get(key) ?? []), index]);
  });
  return merged.map((text, index) => ({ text, index, at: positions.get(collapseWhitespace(text))?.shift() ?? -1 }))
    .sort((a, b) => a.at - b.at || a.index - b.index).map((entry) => entry.text);
}

export function skillPolicyProblems(policy: SkillPolicy, dropped: readonly string[], source: string): string[] {
  return [
    ...policy.pinSkills.filter((name) => policy.dropSkills.includes(name)).map((name) => `policy problem: ${name} is in both ${source} autoCompact.pinSkills and dropSkills; pin wins`),
    ...dropped.filter((name) => policy.pinSkills.includes(name)).map((name) => `drop_skills ${name}: ignored by ${source} autoCompact.pinSkills`),
  ];
}

/**
 * The prompts written since the wake the context holds (userMessages after heldForward), for the early-wake ask.
 * Undefined when it holds none: nothing is then "since the wake", and the whole context (a brief the plugin seated
 * among it) is never read as the person's ask.
 */
export function promptsSinceWake(msgs: readonly ApiMsg[]): string[] | undefined {
  const held = heldForward(msgs);
  return held === undefined ? undefined : userMessages(msgs.slice(held.index + 1));
}
