export type Block = { type: string; [k: string]: unknown };
export type ApiMsg = { role: 'user' | 'assistant'; content: Block[] | string };
export type Invocation = { name: string; baseDir?: string };
export type TrailEntry = { path: string; tag: 'R' | 'E' | 'C' };

const blocksOf = (m: ApiMsg): Block[] => (typeof m.content === 'string' ? [{ type: 'text', text: m.content }] : m.content);
const textOf = (b: Block): string => (typeof b.text === 'string' ? b.text : '');
const inputOf = (b: Block): Record<string, unknown> => (b.input !== null && typeof b.input === 'object' ? (b.input as Record<string, unknown>) : {});
const str = (v: unknown): string | undefined => (typeof v === 'string' && v !== '' ? v : undefined);

/** The text of a tool_result block: its string, or its text blocks joined. */
function resultText(b: Block): string {
  const c = b.content;
  if (typeof c === 'string') return c;
  if (Array.isArray(c)) return c.map((x) => (x !== null && typeof x === 'object' && typeof (x as Block).text === 'string' ? (x as Block).text : '')).join('\n');
  return '';
}

const NOISE = /<(system-reminder|local-command-stdout|local-command-stderr|local-command-caveat|task-notification|user-prompt-submit-hook|bash-stdout|bash-stderr|teammate-message)(?:\s[^>]*)?>[\s\S]*?<\/\1>/g;
const CAVEAT = /Caveat: The messages below were generated by the user while running local commands\.[^\n]*/g;

/** The text without the blocks the harness writes into a user message. */
export function stripNoise(text: string): string {
  return text.replace(NOISE, '').replace(CAVEAT, '');
}

const SKILL_BASE = 'Base directory for this skill:';
const SUMMARY_OPENING = 'This session is being continued from a previous conversation';
const INTERRUPT = /^\[Request interrupted by user[^\]]*\]$/;
const COMMAND_NAME = /<command-name>\s*\/?([^<\s]+)\s*<\/command-name>/;
const COMMAND_ARGS = /<command-args>([\s\S]*?)<\/command-args>/;
const COMMAND_TAGS = /<command-(message|name|args)>[\s\S]*?<\/command-\1>/g;
const COMMAND_MESSAGE = /<command-message>[\s\S]*?<\/command-message>\s*/;
const COMMAND_NAME_TAG = /<command-name>[\s\S]*?<\/command-name>\s*/;
const COMMAND_ARGS_TAG = /<command-args>[\s\S]*?<\/command-args>/;
const LOCAL_OUTPUT = /^\s*<local-command-(?:stdout|stderr)>/;
/** The opening of every notice this plugin writes into a party's context. */
const NOTICE_OPENING = 'sub-agent-compact: ';
/** Commands the client itself runs: no skill or command file stands behind them. */
const BUILTIN = new Set(['clear', 'compact', 'model', 'help', 'config', 'status', 'cost', 'context', 'exit', 'quit', 'resume', 'login', 'logout', 'doctor', 'memory', 'mcp', 'agents', 'hooks', 'plugin', 'plugins', 'reload-plugins', 'permissions', 'vim', 'ide', 'init', 'bug', 'usage', 'rewind', 'export', 'theme', 'terminal-setup', 'add-dir', 'effort']);

/** The cross-chat footer another chat's message carries: not the person's words. */
const FOOTER = /\s+[—–-]\s+sid\s+\S+\s+·\s+to reply:[^\n]*$/;
const IMAGE_TAG = /\[Image #\d+\]\s*/g;
const IMAGE_SOURCE = /\[Image: source: ([^\]\n]+)\]/g;
/** Texts only the harness writes: a tool search's sibling text, an image's size note, a plugin's message to the model, the note after an output cut, and what a sub-agent of this session (an `a` + 16 hex id) sent back. */
const HARNESS_TEXT = /^(?:Tool loaded\.?|\[Image: original [^\]]*\]|The \S+ plugin sent a message:[\s\S]*|Output token limit hit[\s\S]*|Another Claude session sent a message:\s*<agent-message from="a[0-9a-f]{16}">[\s\S]*)$/;

/**
 * The words of the people and parents of the transcript, oldest first: prompts and slash commands with their arguments,
 * an image as `[image <path>]`. What the harness writes into a user message (skill bodies, tool-search notes, image
 * notes, reminders, notifications, a chat's reply footer) is not carried.
 */
export function userMessages(msgs: readonly ApiMsg[]): string[] {
  const out: string[] = [];
  const skillCalls = new Set<string>();
  // The text the harness writes next is a command's or a skill's expansion (its prompt body): not the person's words.
  let expansion = false;
  // An installed handoff leads the context: only the user messages before the first answer can hold one.
  let leading = true;
  for (const m of msgs) {
    if (m.role !== 'user') {
      leading = false;
      expansion = false;
      for (const b of blocksOf(m)) if (b.type === 'tool_use' && b.name === 'Skill' && typeof b.id === 'string') skillCalls.add(b.id);
      continue;
    }
    const parts: string[] = [];
    const sources: string[] = [];
    let pictures = 0;
    for (const b of blocksOf(m)) {
      if (b.type === 'image') {
        pictures++;
        continue;
      }
      if (b.type === 'tool_result') {
        if (typeof b.tool_use_id === 'string' && skillCalls.has(b.tool_use_id)) expansion = true;
        continue;
      }
      if (b.type !== 'text') continue;
      const text = textOf(b);
      if (text.startsWith(SKILL_BASE)) {
        // The harness writes a skill's base line and its body as one text: the expansion is over.
        expansion = false;
        continue;
      }
      if ((leading && text.startsWith(FORWARD_OPENING)) || text.startsWith(SUMMARY_OPENING) || text.startsWith(HANDOFF_OPENING) || text.startsWith(NOTICE_OPENING) || text.startsWith('[sub-agent-compact')) {
        expansion = false;
        continue;
      }
      if (HARNESS_TEXT.test(text.trim())) continue;
      const name = COMMAND_NAME.exec(text)?.[1];
      let said = text;
      if (name !== undefined) {
        const args = COMMAND_ARGS.exec(text)?.[1]?.trim();
        const call = `/${name}${args ? ` ${args}` : ''}`;
        // Only a message that is the command alone is followed by its expansion; one that wraps it in more text (a relay) is carried whole.
        if (text.replace(COMMAND_TAGS, '').trim() === '') {
          parts.push(call);
          expansion = !BUILTIN.has(name);
          continue;
        }
        said = text.replace(COMMAND_MESSAGE, '').replace(COMMAND_NAME_TAG, call).replace(COMMAND_ARGS_TAG, '');
        expansion = false;
      } else if (expansion) {
        expansion = false;
        continue;
      }
      for (const found of said.matchAll(IMAGE_SOURCE)) sources.push(found[1]!.trim());
      const clean = collapseWhitespace(stripNoise(said).replace(IMAGE_SOURCE, '').replace(IMAGE_TAG, '').replace(FOOTER, ''));
      if (clean !== '' && !INTERRUPT.test(clean)) parts.push(clean);
    }
    const markers = sources.map((x) => `[image ${x}]`);
    for (let i = sources.length; i < pictures; i++) markers.push('[image]');
    const joined = collapseWhitespace([...parts, ...markers].join(' '));
    if (parts.length === 0 && markers.length > 0 && out.length > 0 && sources.length > 0) {
      // The source line of a picture arrives as a message of its own, after the prompt that holds the picture.
      // Each named picture takes the place of the first bare marker left, in order; one with none left is added.
      let last = out[out.length - 1]!;
      const extra: string[] = [];
      for (const named of markers) {
        const at = last.indexOf('[image]');
        if (at >= 0) last = `${last.slice(0, at)}${named}${last.slice(at + '[image]'.length)}`;
        else extra.push(named);
      }
      out[out.length - 1] = extra.length > 0 ? `${last} ${extra.join(' ')}` : last;
    } else if (joined !== '') out.push(joined);
  }
  return out;
}

/** The skills and commands invoked, once each, ordered by last use; the directory the harness printed for a skill is kept. */
export function invocations(msgs: readonly ApiMsg[]): Invocation[] {
  const list: Invocation[] = [];
  /** The invocation whose directory the harness prints next, and the Skill call's id whose result may print it; cleared once used and at every model response. */
  let last: Invocation | undefined;
  let skillId: unknown;
  /** A command first seen just now: the client's own output after it means the client ran it, and no file stands behind it. */
  let fresh: Invocation | undefined;
  const invoke = (raw: string, command: boolean): void => {
    const name = oneLineLabel(raw.startsWith('/') ? raw.slice(1) : raw);
    fresh = skillId = undefined;
    if (name === '' || BUILTIN.has(name)) {
      last = undefined;
      return;
    }
    const at = list.findIndex((x) => x.name === name);
    const entry = at >= 0 ? list.splice(at, 1)[0]! : { name };
    list.push(entry);
    last = entry;
    if (command && at < 0) fresh = entry;
  };
  const base = (text: string): void => {
    if (!text.startsWith(SKILL_BASE) || last === undefined) return;
    const dir = text.slice(SKILL_BASE.length).split('\n')[0]!.trim();
    if (dir.startsWith('/')) last.baseDir = dir;
    last = skillId = undefined;
  };
  for (const m of msgs) {
    if (m.role === 'assistant') last = skillId = undefined;
    for (const b of blocksOf(m)) {
      if (m.role === 'assistant' && b.type === 'tool_use' && b.name === 'Skill') {
        const skill = str(inputOf(b).skill);
        if (skill !== undefined) {
          invoke(skill, false);
          skillId = b.id;
        }
      } else if (m.role === 'user' && b.type === 'text') {
        const text = textOf(b);
        const name = COMMAND_NAME.exec(text)?.[1];
        if (name !== undefined) invoke(name, true);
        else if (fresh !== undefined && LOCAL_OUTPUT.test(text)) {
          list.splice(list.indexOf(fresh), 1);
          last = fresh = undefined;
        } else base(text);
      } else if (m.role === 'user' && b.type === 'tool_result' && skillId !== undefined && b.tool_use_id === skillId) base(resultText(b));
    }
  }
  return list;
}

/** The files an invocation may be read from, best first: the directory the harness printed, the project and user roots, every plugin; none for a name that is not one. */
export function invocationPaths(inv: Invocation, roots: WakeRoots): string[] {
  const name = inv.name.startsWith('/') ? inv.name.slice(1) : inv.name;
  if (!WAKE_NAME.test(name)) return [];
  const found = wakeCandidates(name, roots);
  const paths = [...(inv.baseDir !== undefined && !inv.baseDir.includes('..') ? [`${inv.baseDir}/SKILL.md`] : []), ...('paths' in found ? found.paths : [])];
  if (!name.includes(':')) for (const dir of Object.values(roots.plugins)) paths.push(`${dir}/skills/${name}/SKILL.md`, `${dir}/commands/${name}.md`);
  return paths;
}

/** The absolute form of a path: `~/` from home, a relative one from cwd, `.` and `..` resolved. A path that cannot be made absolute stays as it is. */
export function absPath(path: string, cwd: string, home = ''): string {
  let p = path.startsWith('file://') ? path.slice('file://'.length) : path;
  if (p === '~' || p.startsWith('~/')) {
    if (!home.startsWith('/')) return p;
    p = `${home}${p.slice(1)}`;
  } else if (!p.startsWith('/')) {
    if (!cwd.startsWith('/')) return p;
    p = `${cwd}/${p}`;
  }
  const out: string[] = [];
  for (const part of p.split('/')) {
    if (part === '' || part === '.') continue;
    if (part === '..') out.pop();
    else out.push(part);
  }
  return `/${out.join('/')}`;
}

const MASK = '\u0001';

/** A target that is plainly a file path: no quotes, variables, globs or lone words. */
function plainPath(path: string): boolean {
  if (path.startsWith('/dev/') || path.startsWith('/proc/') || !/^(?:~\/|\.{1,2}\/|\/)?[\w@+.\/ -]+$/.test(path)) return false;
  return (path.includes('/') || path.includes('.')) && !/^[\d.]+$/.test(path);
}

/** The files a shell command clearly writes: redirects, tee, sed -i, cp, mv, touch. Quotes and heredoc bodies are never read as commands. */
export function bashWrites(command: string): { path: string; tag: 'E' | 'C'; create: boolean }[] {
  const out: { path: string; tag: 'E' | 'C'; create: boolean }[] = [];
  const quoted: string[] = [];
  const masked = command
    .replace(/<<-?\s*(['"]?)(\w+)\1([^\n]*)\n[\s\S]*?\n\s*\2(?=\s|$)/g, ' $3')
    .replace(/"(?:[^"\\]|\\.)*"|'[^']*'/g, (m) => `${MASK}${quoted.push(m.slice(1, -1)) - 1}${MASK}`);
  const unmask = (token: string): string => token.replace(new RegExp(`${MASK}(\\d+)${MASK}`, 'g'), (_, n: string) => quoted[Number(n)] ?? '');
  const push = (path: string | undefined, create: boolean): void => {
    if (path === undefined || !plainPath(path)) return;
    out.push({ path, tag: create ? 'C' : 'E', create });
  };
  for (const segment of masked.split(/&&|\|\||;|\||\n/)) {
    const t = segment.split(/\s+/).filter(Boolean);
    const args: string[] = [];
    for (let i = 0; i < t.length; i++) {
      const m = /^\d?(>>?)(.*)$/.exec(t[i]!);
      if (m) {
        const target = m[2] !== '' ? m[2] : t[++i];
        if (target !== undefined && !target.startsWith('&')) push(unmask(target), m[1] === '>');
      } else args.push(unmask(t[i]!));
    }
    const [cmd, ...rest] = args;
    const files = rest.filter((x) => !x.startsWith('-'));
    if (cmd === 'tee') push(files[0], !rest.includes('-a'));
    else if (cmd === 'sed' && rest.some((x) => /^-[A-Za-z]*i/.test(x) || x.startsWith('--in-place'))) push(rest.at(-1), false);
    else if ((cmd === 'cp' || cmd === 'mv') && files.length >= 2) push(files.at(-1), true);
    else if (cmd === 'touch') for (const f of files) push(f, true);
  }
  return out;
}

/** The files the tool calls touched, merged, newest touch first, at most `max`. */
export function fileTrail(msgs: readonly ApiMsg[], { cwd, home = '', max = 15 }: { cwd: string; home?: string; max?: number }): TrailEntry[] {
  const seen = new Map<string, { tag: 'R' | 'E' | 'C'; last: number }>();
  let n = 0;
  const touch = (raw: string | undefined, how: 'read' | 'edit' | 'write'): void => {
    if (raw === undefined) return;
    const path = absPath(raw, cwd, home);
    const old = seen.get(path);
    let tag: 'R' | 'E' | 'C';
    if (how === 'read') tag = old?.tag ?? 'R';
    else if (how === 'edit') tag = old?.tag === 'C' ? 'C' : 'E';
    else tag = old === undefined || old.tag === 'C' ? 'C' : 'E';
    seen.set(path, { tag, last: n++ });
  };
  for (const m of msgs) {
    if (m.role !== 'assistant') continue;
    for (const b of blocksOf(m)) {
      if (b.type !== 'tool_use') continue;
      const input = inputOf(b);
      if (b.name === 'Read') touch(str(input.file_path), 'read');
      else if (b.name === 'Edit' || b.name === 'MultiEdit') touch(str(input.file_path), 'edit');
      else if (b.name === 'Write') touch(str(input.file_path), 'write');
      else if (b.name === 'NotebookEdit') touch(str(input.notebook_path), 'edit');
      else if (b.name === 'Bash') for (const w of bashWrites(str(input.command) ?? '')) touch(w.path, w.create ? 'write' : 'edit');
    }
  }
  return [...seen.entries()]
    .sort((a, b) => b[1].last - a[1].last)
    .slice(0, max)
    .map(([path, v]) => ({ tag: v.tag, path }));
}

const STATUS_MARK: Record<string, string> = { completed: '[x]', in_progress: '[~]' };

/** The latest plan (its text from ExitPlanMode, or the plan file written) and the latest task state (TodoWrite, or TaskCreate and TaskUpdate). */
export function planAndTasks(msgs: readonly ApiMsg[]): { planText?: string; planPath?: string; tasks: string[] } {
  const results = new Map<string, string>();
  for (const m of msgs) for (const b of blocksOf(m)) if (b.type === 'tool_result' && typeof b.tool_use_id === 'string') results.set(b.tool_use_id, resultText(b));
  let todos: string[] = [];
  let todoAt = -1;
  const tasks = new Map<string, { subject: string; status: string }>();
  let taskAt = -1;
  let plan: { text?: string; path?: string } | undefined;
  let n = 0;
  for (const m of msgs) {
    for (const b of blocksOf(m)) {
      if (m.role !== 'assistant' || b.type !== 'tool_use') continue;
      n++;
      const input = inputOf(b);
      if (b.name === 'TodoWrite' && Array.isArray(input.todos)) {
        todos = (input.todos as Record<string, unknown>[]).map((t) => `${STATUS_MARK[String(t.status)] ?? '[ ]'} ${String(t.content ?? '')}`);
        todoAt = n;
      } else if (b.name === 'TaskCreate') {
        const id = /#(\d+)/.exec(results.get(String(b.id)) ?? '')?.[1] ?? String(tasks.size + 1);
        tasks.set(id, { subject: String(input.subject ?? ''), status: 'pending' });
        taskAt = n;
      } else if (b.name === 'TaskUpdate') {
        const id = String(input.taskId ?? '');
        const task = tasks.get(id);
        if (task && input.status === 'deleted') tasks.delete(id);
        else if (task && typeof input.status === 'string') task.status = input.status;
        if (typeof input.subject === 'string' && task) task.subject = input.subject;
        taskAt = n;
      } else if (b.name === 'ExitPlanMode' && typeof input.plan === 'string') plan = { text: input.plan };
      else if ((b.name === 'Write' || b.name === 'Edit') && /\/plans\/[^/]+\.md$/.test(String(input.file_path ?? ''))) plan = { path: String(input.file_path) };
    }
  }
  const lines = taskAt > todoAt ? [...tasks.values()].map((t) => `${STATUS_MARK[t.status] ?? '[ ]'} ${t.subject}`) : todos;
  return { ...(plan?.text !== undefined ? { planText: plan.text } : {}), ...(plan?.path !== undefined ? { planPath: plan.path } : {}), tasks: lines };
}

/** The most running-work lines carried: the newest. */
const RUNNING_MAX = 10;

const oneLine = (s: string): string => s.replace(/\s+/g, ' ').trim().slice(0, 80);

/** The engine's own list of what is in flight, as the last turn's end (`classic.Stop`) reported it, and the calls made since. */
export type LiveWork = {
  tasks: { id: string; type: string; description: string; command?: string }[];
  crons: { id: string; schedule: string; recurring: boolean; prompt: string }[];
  /** The `tool_use` ids of every call made since that snapshot: what it could not yet know. */
  started: ReadonlySet<string>;
  /** The time now, in ms: a one-shot cron whose fire time has passed since the snapshot fired and is gone. */
  now?: number;
};

/**
 * Whether a one-shot cron (`minute hour day month *`, local time) has fired by `now`: its fire time is the
 * occurrence nearest to now, so a January time on 31 December is still ahead. False for any other shape.
 */
export function oneShotFired(schedule: string, now: number): boolean {
  const f = /^(\d{1,2}) (\d{1,2}) (\d{1,2}) (\d{1,2}) \*$/.exec(schedule.trim());
  if (!f) return false;
  const year = new Date(now).getFullYear();
  const at = [year - 1, year, year + 1].map((y) => new Date(y, Number(f[4]) - 1, Number(f[3]), Number(f[2]), Number(f[1])).getTime());
  const nearest = at.reduce((a, b) => (Math.abs(b - now) < Math.abs(a - now) ? b : a));
  return nearest <= now;
}

const TASK_LABEL: Record<string, string> = { shell: 'shell', subagent: 'agent', monitor: 'monitor', workflow: 'workflow' };

/**
 * One line per piece of work still running: background shells, sub-agents, monitors, the wakeup and crons armed.
 * With the engine's `live` list, that list is the truth for everything started before it was taken, and the transcript
 * speaks only for the calls since; without it (no turn has ended yet) the transcript alone decides, by the endings it holds.
 */
export function runningWork(msgs: readonly ApiMsg[], live?: LiveWork): string[] {
  const results = new Map<string, string>();
  const ended = new Set<string>();
  let notices = '';
  /** Every later text that says something finished, with where it stands and, for a result, the call it answers. */
  const finishes: { at: number; answers?: string; text: string }[] = [];
  const DONE = /\b(completed|failed|killed|stopped|exited|exit code)\b/i;
  msgs.forEach((m, at) => {
    for (const b of blocksOf(m)) {
      if (b.type === 'tool_result' && typeof b.tool_use_id === 'string') {
        results.set(b.tool_use_id, resultText(b));
        if (DONE.test(resultText(b))) finishes.push({ at, answers: b.tool_use_id, text: resultText(b) });
      } else if (m.role === 'user' && b.type === 'text' && textOf(b).includes('<task-notification')) notices += `${textOf(b)}\n`;
      else if (m.role === 'user' && b.type === 'text' && DONE.test(textOf(b))) finishes.push({ at, text: textOf(b) });
      else if (m.role === 'assistant' && b.type === 'tool_use' && (b.name === 'KillShell' || b.name === 'TaskStop' || b.name === 'CronDelete')) {
        const input = inputOf(b);
        for (const key of ['shell_id', 'task_id', 'id']) if (str(input[key])) ended.add(String(input[key]));
      }
    }
  });
  /** The notifications that end a task: a status other than running. A monitor's event notices carry none. */
  const terminal = (notices.match(/<task-notification>[\s\S]*?<\/task-notification>/g) ?? []).filter((n) => /<status>\s*(?!running)\w+/.test(n));
  const over = (...keys: string[]): boolean => keys.some((k) => ended.has(k) || terminal.some((n) => n.includes(k)));
  const finished = (id: string, at: number, useId: string): boolean => finishes.some((f) => f.at > at && f.answers !== useId && f.text.includes(id));
  const total = msgs.length;
  const out: { at: number; line: string }[] = [];
  /** The ids the transcript lists, so the engine's list adds only what the transcript did not. */
  const listed = new Set<string>();
  let wakeup: { at: number; line: string; id: string } | undefined;
  msgs.forEach((m, at) => {
    if (m.role !== 'assistant') return;
    const age = `${total - 1 - at} msgs ago`;
    for (const b of blocksOf(m)) {
      if (b.type !== 'tool_use') continue;
      const input = inputOf(b);
      const id = String(b.id ?? '');
      // Before the engine's list was taken, the list answers; only a call made since it speaks through the transcript.
      if (live !== undefined && !live.started.has(id)) continue;
      const result = results.get(id);
      const push = (key: string, line: string): void => {
        listed.add(key);
        out.push({ at, line });
      };
      if (b.name === 'Bash' && input.run_in_background === true) {
        const shell = /background with ID:\s*([A-Za-z0-9_-]+)/.exec(result ?? '')?.[1] ?? id.slice(-8);
        if (!over(shell, id) && !finished(shell, at, id)) push(shell, `shell ${shell}: ${oneLine(String(input.command ?? ''))}, ${age}`);
      } else if (b.name === 'Agent' || b.name === 'Task') {
        const background = input.run_in_background === true;
        if (!background && result !== undefined) continue;
        const agent = /agentId:\s*([A-Za-z0-9]+)/.exec(result ?? '')?.[1] ?? id.slice(-8);
        if (!over(agent, id) && !(background && finished(agent, at, id))) push(agent, `agent ${agent}: ${oneLine(String(input.description ?? input.prompt ?? ''))}, ${age}`);
      } else if (b.name === 'Monitor') {
        const task = /\(task ([A-Za-z0-9]+)/.exec(result ?? '')?.[1] ?? id.slice(-8);
        if (!over(task, id)) push(task, `monitor ${task}: ${oneLine(String(input.description ?? input.command ?? ''))}, ${age}`);
      } else if (b.name === 'ScheduleWakeup') {
        const cron = /(?:task|job)\s+([A-Za-z0-9]{6,})/.exec(result ?? '')?.[1] ?? '';
        if (cron === '' || !over(cron)) wakeup = { at, line: `wakeup: ${oneLine(String(input.reason ?? input.prompt ?? ''))}, ${age}`, id: cron };
      } else if (b.name === 'CronCreate') {
        const cron = /(?:task|job)\s+([A-Za-z0-9]{6,})/.exec(result ?? '')?.[1] ?? '';
        if (cron === '' || !over(cron)) push(cron, `cron${cron !== '' ? ` ${cron}` : ''}: ${oneLine(`${String(input.cron ?? '')} ${String(input.prompt ?? '')}`)}, ${age}`);
      }
    }
  });
  if (wakeup) {
    out.push({ at: wakeup.at, line: wakeup.line });
    listed.add(wakeup.id);
  }
  const lines = out.sort((a, b) => a.at - b.at).map((x) => x.line);
  if (live !== undefined) {
    const mine = [
      ...live.tasks.filter((t) => !listed.has(t.id) && !over(t.id)).map((t) => `${TASK_LABEL[t.type] ?? t.type} ${t.id}: ${oneLine(t.command ?? t.description)}`),
      ...live.crons.filter((c) => !listed.has(c.id) && !over(c.id) && (c.recurring || live.now === undefined || !oneShotFired(c.schedule, live.now))).map((c) => `cron ${c.id}${c.recurring ? '' : ' once'}: ${oneLine(`${c.schedule} ${c.prompt}`)}`),
    ];
    return [...mine, ...lines].slice(-RUNNING_MAX);
  }
  return lines.slice(-RUNNING_MAX);
}

/** The paths of `git status --porcelain`, a rename as its target, absolute under `root` (the repository's top, where porcelain paths start). */
export function parsePorcelain(out: string, root = ''): string[] {
  const paths: string[] = [];
  for (const line of out.split('\n')) {
    if (line.length < 4) continue;
    let path = line.slice(3);
    const arrow = path.indexOf(' -> ');
    if (arrow >= 0) path = path.slice(arrow + 4);
    path = path.replace(/^"(.*)"$/, '$1');
    paths.push(root !== '' ? absPath(path, root) : path);
  }
  return paths;
}

const GIT_PATHS = 10;

/** `branch@head, N dirty: a, b…` on one line, with at most 10 paths. */
export function gitLine({ branch, head, dirty }: { branch: string; head: string; dirty: readonly string[] }): string {
  if (dirty.length === 0) return `${branch}@${head}, clean`;
  return `${branch}@${head}, ${dirty.length} dirty: ${dirty.slice(0, GIT_PATHS).join(', ')}${dirty.length > GIT_PATHS ? '…' : ''}`;
}

/** A `load_files` range: `10-20`, `10:20` or `7`, one-based and inclusive; undefined when it is not one. */
export function parseLineRange(text: string): { from: number; to: number } | undefined {
  const m = /^\s*(\d+)\s*(?:[-:]\s*(\d+))?\s*$/.exec(text);
  if (!m) return undefined;
  const from = Number(m[1]);
  const to = m[2] === undefined ? from : Number(m[2]);
  return from >= 1 && to >= from ? { from, to } : undefined;
}

export function sliceLines(text: string, range: { from: number; to: number }): string {
  return text.split('\n').slice(range.from - 1, range.to).join('\n');
}

/** The command that finds a transcript by its session id, the way Claude Code placed it: the project directory is whatever Claude Code named it. `-H`: a `projects` that is a link to the real directory is searched through. */
export function findTranscriptArgv({ configDir, session, agentId }: { configDir: string; session: string; agentId?: string }): string[] {
  const projects = `${configDir}/projects`;
  return agentId === undefined
    ? ['find', '-H', projects, '-maxdepth', '2', '-type', 'f', '-name', `${session}.jsonl`]
    : ['find', '-H', projects, '-maxdepth', '4', '-type', 'f', '-path', `*/${session}/subagents/agent-${agentId}.jsonl`];
}

/** The path `find` printed first, or undefined when it printed none. */
export function firstFound(stdout: string): string | undefined {
  return stdout.split('\n').find((line) => line.startsWith('/'));
}

/**
 * The forward handoff the party holds, with the message it is in: the newest text a record of this party holds
 * (`recorded`), else the one leading the context, where an install puts it. A text opening like one anywhere else
 * is a person's message. Undefined when there is none.
 */
export function heldForward(msgs: readonly ApiMsg[], recorded?: (text: string) => boolean): { text: string; index: number; recorded: boolean } | undefined {
  const firstAnswer = msgs.findIndex((m) => m.role === 'assistant');
  const leadEnd = firstAnswer < 0 ? msgs.length : firstAnswer;
  let leading: { text: string; index: number; recorded: boolean } | undefined;
  for (let i = msgs.length - 1; i >= 0; i--) {
    const m = msgs[i]!;
    if (m.role !== 'user') continue;
    for (const b of blocksOf(m)) {
      if (b.type !== 'text' || !textOf(b).startsWith(FORWARD_OPENING)) continue;
      if (recorded?.(textOf(b))) return { text: textOf(b), index: i, recorded: true };
      if (i < leadEnd && leading === undefined) leading = { text: textOf(b), index: i, recorded: false };
    }
  }
  return leading;
}

/**
 * The user entries of a transcript before its last compaction, from `grep -n` lines of the JSONL file, as messages
 * userMessages reads: Claude Code's own summary replaced them in the context, the file still holds them. A command's
 * or skill's expansion (isMeta) and a summary are left out; each entry stands alone, so none reads as another's expansion.
 */
export function priorPrompts(grepLines: string, boundaryLine: number): ApiMsg[] {
  const out: ApiMsg[] = [];
  for (const line of grepLines.split('\n')) {
    const m = /^(\d+):(.*)$/.exec(line);
    if (m === null || Number(m[1]) >= boundaryLine) continue;
    let entry: { type?: unknown; isMeta?: unknown; isCompactSummary?: unknown; message?: { role?: unknown; content?: unknown } };
    try {
      entry = JSON.parse(m[2]!);
    } catch {
      continue;
    }
    if (entry.type !== 'user' || entry.isMeta === true || entry.isCompactSummary === true || entry.message === undefined) continue;
    const content = entry.message.content;
    if (typeof content !== 'string' && !Array.isArray(content)) continue;
    out.push({ role: 'user', content: content as ApiMsg['content'] });
    out.push({ role: 'assistant', content: [] });
  }
  return out;
}

/**
 * The model's tool calls before a transcript's last compaction, from `grep -n` lines of the JSONL file, as messages
 * fileTrail reads: Claude Code's own summary replaced them in the context, the file still holds them.
 */
export function priorCalls(grepLines: string, boundaryLine: number): ApiMsg[] {
  const out: ApiMsg[] = [];
  for (const line of grepLines.split('\n')) {
    const m = /^(\d+):(.*)$/.exec(line);
    if (m === null || Number(m[1]) >= boundaryLine) continue;
    let entry: { type?: unknown; message?: { content?: unknown } };
    try {
      entry = JSON.parse(m[2]!);
    } catch {
      continue;
    }
    const content = entry.message?.content;
    if (entry.type !== 'assistant' || !Array.isArray(content)) continue;
    out.push({ role: 'assistant', content: content as ApiMsg['content'] });
  }
  return out;
}

/**
 * Two trails as one, at most `max`: the newer one's files first, then the older one's it lacks. A file the older trail
 * created stays created; one touched in both is edited unless both only read it.
 */
export function mergeTrail(older: readonly TrailEntry[] | undefined, newer: readonly TrailEntry[], max: number): TrailEntry[] {
  const before = new Map((older ?? []).map((t) => [t.path, t.tag] as const));
  const merged = newer.map((t): TrailEntry => {
    const old = before.get(t.path);
    if (old === undefined) return t;
    return { tag: old === 'C' ? 'C' : old === 'R' && t.tag === 'R' ? 'R' : 'E', path: t.path };
  });
  for (const t of older ?? []) if (!newer.some((n) => n.path === t.path)) merged.push(t);
  return merged.slice(0, max);
}

/** The calls a model makes to reach the forward handoff itself: they do no work on a request. */
const reachesHandoff = (name: unknown): boolean => name === 'ToolSearch' || (typeof name === 'string' && name.endsWith(FORWARD_TOOL));

/**
 * Whether the forward handoff call is the reply to the latest prompt: after it the model did nothing but reach for the
 * handoff. A nudged handoff comes after work on the prompt, so it is not one.
 */
export function handoffInReply(msgs: readonly ApiMsg[]): boolean {
  let worked = -1;
  for (let i = msgs.length - 1; i >= 0 && worked < 0; i--) {
    const m = msgs[i]!;
    if (m.role === 'assistant' && blocksOf(m).some((b) => b.type === 'tool_use' && !reachesHandoff(b.name))) worked = i;
  }
  return userMessages(msgs.slice(worked + 1)).length > 0;
}

/**
 * Whether the context opens with Claude Code's own summary: the prompts before it are then only in the transcript file.
 * The reminders Claude Code re-sends after a compaction (CLAUDE.md, session context, date) come before it.
 */
export function opensWithSummary(msgs: readonly ApiMsg[]): boolean {
  return openingSummary(msgs) !== undefined;
}

/** Claude Code's own summary when the context opens with it (past the reminders it puts first), else undefined. */
export function openingSummary(msgs: readonly ApiMsg[]): string | undefined {
  for (const m of msgs) {
    if (m.role !== 'user') return undefined;
    for (const b of blocksOf(m)) {
      if (b.type !== 'text' || textOf(b).trimStart().startsWith('<system-reminder>')) continue;
      return textOf(b).startsWith(SUMMARY_OPENING) ? textOf(b) : undefined;
    }
  }
  return undefined;
}

/** The sections of Claude Code's summary that hold what it knew; the request, prompts, tasks, current work and next step are carried newer elsewhere. */
const KNOWLEDGE = new Set(['Key Technical Concepts', 'Files and Code Sections', 'Errors and fixes', 'Problem Solving']);
const SECTION = /^\d+\.\s+(.+?):\s*$/;
const CLOSING = /^(?:If you need specific details from before compaction|Continue the conversation from where it left off|The messages after this summary are)/;

/** What Claude Code's summary knew, as `Section:` then its lines, dedented, blank lines dropped; undefined when it has none of those sections. */
export function summaryKnowledge(summary: string): string | undefined {
  const out: string[] = [];
  let keep = false;
  for (const line of summary.replace(/\r\n?/g, '\n').split('\n')) {
    if (CLOSING.test(line)) break;
    const head = SECTION.exec(line);
    if (head !== null) {
      keep = KNOWLEDGE.has(head[1]!.trim());
      if (keep) out.push(`${head[1]!.trim()}:`);
      continue;
    }
    if (keep && line.trim() !== '') out.push(line.replace(/^ {1,3}/, '').trimEnd());
  }
  return out.length > 0 ? out.join('\n') : undefined;
}

/** The longest outline line, and the per-language patterns whose first non-empty group names a symbol. */
export const OUTLINE_LINE_MAX = 400;
/** A file larger than this is named without an outline: reading it whole at every handoff costs more than its names give. */
export const OUTLINE_FILE_MAX_BYTES = 1024 * 1024;
const TS = [/^export\s+(?:default\s+)?(?:declare\s+)?(?:abstract\s+)?(?:async\s+)?(?:function\*?|const|let|var|class|type|interface|enum)\s+([A-Za-z_$][\w$]*)/, /^(?:async\s+)?function\*?\s+([A-Za-z_$][\w$]*)/, /^(?:abstract\s+)?(?:class|interface|type|enum)\s+([A-Za-z_$][\w$]*)/];
const TESTS = [/^\s*(?:describe|it|test)(?:\.\w+)?\(\s*(['"`])(.+?)\1/];
const OUTLINE_RULES: [RegExp, RegExp[]][] = [
  [/\.(?:test|spec)\.[cm]?[jt]sx?$/, [...TESTS, ...TS]],
  [/\.[cm]?[jt]sx?$/, TS],
  [/\.go$/, [/^func\s+\(\s*\w*\s*\*?(\w+)[^)]*\)\s*(\w+)/, /^func\s+(\w+)/, /^type\s+(\w+)/]],
  [/\.pyi?$/, [/^(?:async\s+)?def\s+(\w+)/, /^class\s+(\w+)/]],
  [/\.rs$/, [/^(?:pub(?:\([^)]*\))?\s+)?(?:async\s+)?(?:fn|struct|enum|trait|type|mod)\s+(\w+)/]],
  [/(?:\.(?:sh|bash|zsh)|\/[^/.]+)$/, [/^(?:function\s+)?([\w-]+)\s*\(\)\s*\{/, /^function\s+([\w-]+)\s*\{/]],
  [/\.(?:md|mdx|markdown)$/, [/^#{1,3}\s+(.+?)\s*#*$/]],
  [/\.ya?ml$/, [/^([\w.-]+):/]],
  [/\.toml$/, [/^\[\[?([^\]]+)\]/]],
];

/**
 * What a file defines, as one line: its line count, then the names it declares at top level, in order and once each —
 * exports, functions, types and classes; Go methods as `Type.Name`; test names; Markdown headings to depth 3; top-level
 * keys of JSON, YAML and TOML. A file of no known kind, or one whose names cannot be read, gives its line count alone.
 */
export function outline(path: string, text: string, max = OUTLINE_LINE_MAX): string {
  const lines = text.replace(/\r\n?/g, '\n').split('\n');
  if (lines.at(-1) === '') lines.pop();
  const names: string[] = [];
  const add = (name: string): void => {
    const one = name.trim();
    if (one !== '' && !names.includes(one)) names.push(one);
  };
  if (/\.json$/.test(path)) {
    try {
      const parsed: unknown = JSON.parse(text);
      if (parsed !== null && typeof parsed === 'object' && !Array.isArray(parsed)) Object.keys(parsed).forEach(add);
    } catch {
      // Not JSON as it stands: the line count alone says the file is there.
    }
  } else {
    const rules = OUTLINE_RULES.find(([kind]) => kind.test(path))?.[1] ?? [];
    const markdown = /\.(?:md|mdx|markdown)$/.test(path);
    let fenced = false;
    for (const line of lines) {
      if (markdown && /^\s*(?:```|~~~)/.test(line)) fenced = !fenced;
      if (fenced) continue;
      for (const rule of rules) {
        const m = rule.exec(line);
        if (m === null) continue;
        const groups = m.slice(1).filter((g): g is string => g !== undefined && g !== '' && !/^['"`]$/.test(g));
        add(groups.length === 2 && rule.source.startsWith('^func') ? `${groups[0]}.${groups[1]}` : (groups[0] ?? ''));
        break;
      }
    }
  }
  const head = `${lines.length} lines`;
  if (names.length === 0) return head;
  let body = `${head}: ${names[0]}`;
  for (let n = 1; n < names.length; n++) {
    const more = `, +${names.length - n} more`;
    const next = `${body}, ${names[n]}`;
    const last = n === names.length - 1;
    if ((last ? next.length : next.length + `, +${names.length - n - 1} more`.length) > max) return `${body}${more}`;
    body = next;
  }
  return body;
}
