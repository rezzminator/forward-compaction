/** The cross-chat footer another chat's message carries: not the person's words. */
const FOOTER = /\s+[—–-]\s+sid\s+\S+\s+·\s+to reply:[^\n]*$/;
const IMAGE_TAG = /\[Image #\d+\]\s*/g;
const IMAGE_SOURCE = /\[Image: source: ([^\]\n]+)\]/g;
/** Texts only the harness writes: a tool search's sibling text, an image's size note, a plugin's message to the model, the note after an output cut, and what a sub-agent of this session (an `a` + 16 hex id) sent back. */
const HARNESS_TEXT = /^(?:Tool loaded\.?|\[Image: original [^\]]*\]|The \S+ plugin sent a message:[\s\S]*|Output token limit hit[\s\S]*|Another Claude session sent a message:\s*<agent-message from="a[0-9a-f]{16}">[\s\S]*)$/;

/** The headers Claude Code opens a message with when it reaches a party mid-turn: the coordinator's, the person's, another agent's. */
const QUEUED_HEADS = ['The coordinator sent a message while you were working:', 'The user sent a new message while you were working:', 'Another Claude session sent a message while you were working:'] as const;
const QUEUED = /<system-reminder(?:\s[^>]*)?>\s*(The coordinator sent a message while you were working:|The user sent a new message while you were working:|Another Claude session sent a message while you were working:)\n([\s\S]*?)\s*<\/system-reminder(?:\s[^>]*)?>/g;
const COORDINATOR_TAIL = /\n\nAddress this before completing your current task\.\s*$/;
const PERSON_TAIL = /\n\nThis is how Claude Code surfaces messages the user sends mid-turn[\s\S]*$/;
const AGENT_MESSAGE = /^<agent-message from="([^"]+)">\n?([\s\S]*?)\n?<\/agent-message>/;

/**
 * A message delivered mid-turn, as carried: the coordinator's (the main chat that spawned this agent) under its header;
 * the person's as their words alone; another agent's only when it is the party's parent (`parent`: its id or name),
 * under a header naming it. Undefined for any other agent's: a report or request, not an instruction.
 */
function queuedMessage(head: string, inner: string, parent: readonly string[]): string | undefined {
  if (head === QUEUED_HEADS[0]) return `${head}\n${inner.replace(COORDINATOR_TAIL, '').trim()}`;
  if (head === QUEUED_HEADS[1]) return inner.replace(PERSON_TAIL, '').trim();
  const m = AGENT_MESSAGE.exec(inner.trim());
  if (m === null || !parent.includes(m[1]!)) return undefined;
  return `The parent agent ${m[1]} sent a message while you were working:\n${m[2]!.trim()}`;
}

/** The mid-turn messages a text holds, wrapped in a reminder or plain, and the text left without them. */
function takeQueued(text: string, parent: readonly string[]): { messages: string[]; rest: string; found: boolean } {
  const messages: string[] = [];
  const plain = QUEUED_HEADS.find((head) => text.trimStart().startsWith(head));
  if (plain !== undefined) {
    const said = queuedMessage(plain, text.trimStart().slice(plain.length).replace(/^\n/, ''), parent);
    return { messages: said !== undefined && said.trim() !== '' ? [said] : [], rest: '', found: true };
  }
  let found = false;
  const rest = text.replace(QUEUED, (_all, head: string, inner: string) => {
    found = true;
    const said = queuedMessage(head, inner, parent);
    if (said !== undefined && said.trim() !== '') messages.push(said);
    return '';
  });
  return { messages, rest, found };
}

/** Options of the user-message carry: the party's parent agent, by id and name, whose mid-turn messages are instructions. */
export type CarryOptions = { parent?: readonly string[]; delivered?: readonly string[] };

/**
 * The words of the people and parents of the transcript, oldest first: prompts and slash commands with their arguments,
 * an image as `[image <path>]`. What the harness writes into a user message (skill bodies, tool-search notes, image
 * notes, reminders, notifications, a chat's reply footer) is not carried.
 */
export function userMessages(msgs: readonly ApiMsg[], opts: CarryOptions = {}): string[] {
  return userEntries(msgs, opts).map((e) => e.text);
}

/** The user messages with whether each reached the party mid-turn (a queued message), for handoffInReply, and the index of the message holding it. */
function userEntries(msgs: readonly ApiMsg[], { parent = [], delivered = [] }: CarryOptions): { text: string; queued: boolean; at: number }[] {
  const out: { text: string; queued: boolean; at: number }[] = [];
  const carried = delivered.map(collapseWhitespace);
  const skillCalls = new Set<string>();
  // The text the harness writes next is a command's or a skill's expansion (its prompt body): not the person's words.
  let expansion = false;
  for (const [at, m] of msgs.entries()) {
    if (m.role !== 'user') {
      expansion = false;
      for (const b of blocksOf(m)) if (b.type === 'tool_use' && b.name === 'Skill' && typeof b.id === 'string') skillCalls.add(b.id);
      continue;
    }
    const parts: string[] = [];
    const sources: string[] = [];
    const queued: string[] = [];
    let pictures = 0;
    for (const b of blocksOf(m)) {
      if (b.type === 'image') {
        pictures++;
        continue;
      }
      if (b.type === 'tool_result') {
        if (typeof b.tool_use_id === 'string' && skillCalls.has(b.tool_use_id)) expansion = true;
        continue;
      }
      if (b.type !== 'text') continue;
      // A message the parent or the person sent mid-turn rides beside a tool result: carried as theirs, never an expansion.
      const taken = takeQueued(textOf(b), parent);
      queued.push(...taken.messages);
      if (taken.found && taken.rest.trim() === '') continue;
      const text = taken.found ? taken.rest : textOf(b);
      if (text.startsWith(SKILL_BASE)) {
        // The harness writes a skill's base line and its body as one text: the expansion is over.
        expansion = false;
        continue;
      }
      if (text.startsWith(FORWARD_OPENING) || text.startsWith(SUMMARY_OPENING) || text.startsWith(HANDOFF_OPENING) || text.startsWith(NOTICE_OPENING) || text.startsWith('[sub-agent-compact')) {
        expansion = false;
        continue;
      }
      if (HARNESS_TEXT.test(text.trim())) continue;
      const name = COMMAND_NAME.exec(text)?.[1];
      let said = text;
      if (name !== undefined) {
        const args = COMMAND_ARGS.exec(text)?.[1]?.trim();
        const call = `/${name}${args ? ` ${args}` : ''}`;
        // Only a message that is the command alone is followed by its expansion; one that wraps it in more text (a relay) is carried whole.
        if (text.replace(COMMAND_TAGS, '').trim() === '') {
          parts.push(call);
          expansion = !BUILTIN.has(name);
          continue;
        }
        said = text.replace(COMMAND_MESSAGE, '').replace(COMMAND_NAME_TAG, call).replace(COMMAND_ARGS_TAG, '');
        expansion = false;
      } else if (expansion) {
        expansion = false;
        continue;
      }
      for (const found of said.matchAll(IMAGE_SOURCE)) sources.push(found[1]!.trim());
      const clean = collapseWhitespace(stripNoise(said).replace(IMAGE_SOURCE, '').replace(IMAGE_TAG, '').replace(FOOTER, ''));
      if (clean !== '' && !INTERRUPT.test(clean)) parts.push(clean);
    }
    const markers = sources.map((x) => `[image ${x}]`);
    for (let i = sources.length; i < pictures; i++) markers.push('[image]');
    const joined = collapseWhitespace([...parts, ...markers].join(' '));
    if (parts.length === 0 && markers.length > 0 && out.length > 0 && sources.length > 0) {
      // The source line of a picture arrives as a message of its own, after the prompt that holds the picture.
      // Each named picture takes the place of the first bare marker left, in order; one with none left is added.
      let last = out[out.length - 1]!.text;
      const extra: string[] = [];
      for (const named of markers) {
        const at = last.indexOf('[image]');
        if (at >= 0) last = `${last.slice(0, at)}${named}${last.slice(at + '[image]'.length)}`;
        else extra.push(named);
      }
      out[out.length - 1] = { ...out[out.length - 1]!, text: extra.length > 0 ? `${last} ${extra.join(' ')}` : last };
    } else if (joined !== '') out.push({ text: joined, queued: false, at });
    for (const said of queued) {
      const text = collapseWhitespace(said);
      const seen = carried.indexOf(text);
      if (seen >= 0) carried.splice(seen, 1);
      else out.push({ text, queued: true, at });
    }
  }
  return out;
}

/** The skills and commands invoked, once each, ordered by last use; the directory the harness printed for a skill is kept. */
export function invocations(msgs: readonly ApiMsg[]): Invocation[] {
  const list: Invocation[] = [];
  /** The invocation whose directory the harness prints next, and the Skill call's id whose result may print it; cleared once used and at every model response. */
  let last: Invocation | undefined;
  let skillId: unknown;
  /** A command first seen just now: the client's own output after it means the client ran it, and no file stands behind it. */
  let fresh: Invocation | undefined;
  const invoke = (raw: string, command: boolean): void => {
    const name = oneLineLabel(raw.startsWith('/') ? raw.slice(1) : raw);
    fresh = skillId = undefined;
    if (name === '' || BUILTIN.has(name)) {
      last = undefined;
      return;
    }
    const at = list.findIndex((x) => x.name === name);
    const entry = at >= 0 ? list.splice(at, 1)[0]! : { name };
    list.push(entry);
    last = entry;
    if (command && at < 0) fresh = entry;
  };
  const base = (text: string): void => {
    if (!text.startsWith(SKILL_BASE) || last === undefined) return;
    const dir = text.slice(SKILL_BASE.length).split('\n')[0]!.trim();
    if (dir.startsWith('/')) last.baseDir = dir;
    last = skillId = undefined;
  };
  for (const m of msgs) {
    if (m.role === 'assistant') last = skillId = undefined;
    for (const b of blocksOf(m)) {
      if (m.role === 'assistant' && b.type === 'tool_use' && b.name === 'Skill') {
        const skill = str(inputOf(b).skill);
        if (skill !== undefined) {
          invoke(skill, false);
          skillId = b.id;
        }
      } else if (m.role === 'user' && b.type === 'text') {
        const text = textOf(b);
        const name = COMMAND_NAME.exec(text)?.[1];
        if (name !== undefined) invoke(name, true);
        else if (fresh !== undefined && LOCAL_OUTPUT.test(text)) {
          list.splice(list.indexOf(fresh), 1);
          last = fresh = undefined;
        } else base(text);
      } else if (m.role === 'user' && b.type === 'tool_result' && skillId !== undefined && b.tool_use_id === skillId) base(resultText(b));
    }
  }
  return list;
}

/** The files an invocation may be read from, best first: the directory the harness printed, the project and user roots, every plugin; none for a name that is not one. */
export function invocationPaths(inv: Invocation, roots: WakeRoots): string[] {
  const name = inv.name.startsWith('/') ? inv.name.slice(1) : inv.name;
  if (!WAKE_NAME.test(name)) return [];
  const found = wakeCandidates(name, roots);
  const paths = [...(inv.baseDir !== undefined && !inv.baseDir.includes('..') ? [`${inv.baseDir}/SKILL.md`] : []), ...('paths' in found ? found.paths : [])];
  if (!name.includes(':')) for (const dir of Object.values(roots.plugins)) paths.push(`${dir}/skills/${name}/SKILL.md`, `${dir}/commands/${name}.md`);
  return paths;
}

/** The absolute form of a path: `~/` from home, a relative one from cwd, `.` and `..` resolved. A path that cannot be made absolute stays as it is. */
export function absPath(path: string, cwd: string, home = ''): string {
  let p = path.startsWith('file://') ? path.slice('file://'.length) : path;
  if (p === '~' || p.startsWith('~/')) {
    if (!home.startsWith('/')) return p;
    p = `${home}${p.slice(1)}`;
  } else if (!p.startsWith('/')) {
    if (!cwd.startsWith('/')) return p;
    p = `${cwd}/${p}`;
  }
  const out: string[] = [];
  for (const part of p.split('/')) {
    if (part === '' || part === '.') continue;
    if (part === '..') out.pop();
    else out.push(part);
  }
  return `/${out.join('/')}`;
}

const MASK = '\u0001';

/** A target that is plainly a file path: no quotes, variables, globs or lone words. */
function plainPath(path: string): boolean {
  if (path.startsWith('/dev/') || path.startsWith('/proc/') || !/^(?:~\/|\.{1,2}\/|\/)?[\w@+.\/ -]+$/.test(path)) return false;
  return (path.includes('/') || path.includes('.')) && !/^[\d.]+$/.test(path);
}

/** The files a shell command clearly writes: redirects, tee, sed -i, cp, mv, touch. Quotes and heredoc bodies are never read as commands. */
export function bashWrites(command: string): { path: string; tag: 'E' | 'C'; create: boolean }[] {
  const out: { path: string; tag: 'E' | 'C'; create: boolean }[] = [];
  const quoted: string[] = [];
  const masked = command
    .replace(/<<-?\s*(['"]?)(\w+)\1([^\n]*)\n[\s\S]*?\n\s*\2(?=\s|$)/g, ' $3')
    .replace(/"(?:[^"\\]|\\.)*"|'[^']*'/g, (m) => `${MASK}${quoted.push(m.slice(1, -1)) - 1}${MASK}`);
  const unmask = (token: string): string => token.replace(new RegExp(`${MASK}(\\d+)${MASK}`, 'g'), (_, n: string) => quoted[Number(n)] ?? '');
  // Where a relative path lands after a `cd` in the same command: undefined before any, null after one it cannot place.
  let dir: string | null | undefined;
  const push = (path: string | undefined, create: boolean): void => {
    if (path === undefined || !plainPath(path)) return;
    const relative = !path.startsWith('/') && !path.startsWith('~');
    if (relative && dir === null) return;
    const placed = relative && dir !== undefined ? `${dir}/${path.replace(/^\.\//, '')}` : path;
    out.push({ path: placed, tag: create ? 'C' : 'E', create });
  };
  for (const segment of masked.split(/&&|\|\||;|\||\n/)) {
    const t = segment.replace(/^\s*\(+/, '').split(/\s+/).filter(Boolean);
    if (t[0] === 'cd') {
      const to = t[1] === undefined ? '~' : unmask(t[1]).replace(/\)+$/, '');
      const placeable = /^[\w@+.\/~-]+$/.test(to);
      if (to === '~' || to === '/' || (placeable && (to.startsWith('/') || to.startsWith('~/')))) dir = to.replace(/\/+$/, '') || '/';
      else if (dir !== null && placeable) dir = `${dir === undefined ? '' : `${dir}/`}${to.replace(/^\.\//, '').replace(/\/+$/, '')}`;
      else dir = null;
      continue;
    }
    const args: string[] = [];
    for (let i = 0; i < t.length; i++) {
      const m = /^\d?(>>?)(.*)$/.exec(t[i]!);
      if (m) {
        const target = m[2] !== '' ? m[2] : t[++i];
        if (target !== undefined && !target.startsWith('&')) push(unmask(target).replace(/\)+$/, ''), m[1] === '>');
      } else args.push(unmask(t[i]!));
    }
    const [cmd, ...rest] = args;
    const files = rest.filter((x) => !x.startsWith('-'));
    if (cmd === 'tee') push(files[0], !rest.includes('-a'));
    else if (cmd === 'sed' && rest.some((x) => /^-[A-Za-z]*i/.test(x) || x.startsWith('--in-place'))) push(rest.at(-1), false);
    else if ((cmd === 'cp' || cmd === 'mv') && files.length >= 2) push(files.at(-1), true);
    else if (cmd === 'touch') for (const f of files) push(f, true);
  }
  return out;
}

/** The files the tool calls touched, merged, newest touch first, at most `max`. */
export function fileTrail(msgs: readonly ApiMsg[], { cwd, home = '', max = 15 }: { cwd: string; home?: string; max?: number }): TrailEntry[] {
  const seen = new Map<string, { tag: 'R' | 'E' | 'C'; last: number }>();
  let n = 0;
  const touch = (raw: string | undefined, how: 'read' | 'edit' | 'write'): void => {
    if (raw === undefined) return;
    const path = absPath(raw, cwd, home);
    const old = seen.get(path);
    let tag: 'R' | 'E' | 'C';
    if (how === 'read') tag = old?.tag ?? 'R';
    else if (how === 'edit') tag = old?.tag === 'C' ? 'C' : 'E';
    else tag = old === undefined || old.tag === 'C' ? 'C' : 'E';
    seen.set(path, { tag, last: n++ });
  };
  for (const m of msgs) {
    if (m.role !== 'assistant') continue;
    for (const b of blocksOf(m)) {
      if (b.type !== 'tool_use') continue;
      const input = inputOf(b);
      if (b.name === 'Read') touch(str(input.file_path), 'read');
      else if (b.name === 'Edit' || b.name === 'MultiEdit') touch(str(input.file_path), 'edit');
      else if (b.name === 'Write') touch(str(input.file_path), 'write');
      else if (b.name === 'NotebookEdit') touch(str(input.notebook_path), 'edit');
      else if (b.name === 'Bash') for (const w of bashWrites(str(input.command) ?? '')) touch(w.path, w.create ? 'write' : 'edit');
    }
  }
  return [...seen.entries()]
    .sort((a, b) => b[1].last - a[1].last)
    .slice(0, max)
    .map(([path, v]) => ({ tag: v.tag, path }));
}

const STATUS_MARK: Record<string, string> = { completed: '[x]', in_progress: '[~]' };

/** The latest plan (its text from ExitPlanMode, or the plan file written) and the latest task state (TodoWrite, or TaskCreate and TaskUpdate). */
export function planAndTasks(msgs: readonly ApiMsg[]): { planText?: string; planPath?: string; tasks: string[] } {
  const results = new Map<string, string>();
  for (const m of msgs) for (const b of blocksOf(m)) if (b.type === 'tool_result' && typeof b.tool_use_id === 'string') results.set(b.tool_use_id, resultText(b));
  let todos: string[] = [];
  let todoAt = -1;
  const tasks = new Map<string, { subject: string; status: string }>();
  let taskAt = -1;
  let plan: { text?: string; path?: string } | undefined;
  let n = 0;
  for (const m of msgs) {
    for (const b of blocksOf(m)) {
      if (m.role !== 'assistant' || b.type !== 'tool_use') continue;
      n++;
      const input = inputOf(b);
      if (b.name === 'TodoWrite' && Array.isArray(input.todos)) {
        todos = (input.todos as Record<string, unknown>[]).map((t) => `${STATUS_MARK[String(t.status)] ?? '[ ]'} ${String(t.content ?? '')}`);
        todoAt = n;
      } else if (b.name === 'TaskCreate') {
        const id = /#(\d+)/.exec(results.get(String(b.id)) ?? '')?.[1] ?? String(tasks.size + 1);
        tasks.set(id, { subject: String(input.subject ?? ''), status: 'pending' });
        taskAt = n;
      } else if (b.name === 'TaskUpdate') {
        const id = String(input.taskId ?? '');
        const task = tasks.get(id);
        if (task && input.status === 'deleted') tasks.delete(id);
        else if (task && typeof input.status === 'string') task.status = input.status;
        if (typeof input.subject === 'string' && task) task.subject = input.subject;
        taskAt = n;
      } else if (b.name === 'ExitPlanMode' && typeof input.plan === 'string') plan = { text: input.plan };
      else if ((b.name === 'Write' || b.name === 'Edit') && /\/plans\/[^/]+\.md$/.test(String(input.file_path ?? ''))) plan = { path: String(input.file_path) };
    }
  }
  const lines = taskAt > todoAt ? [...tasks.values()].map((t) => `${STATUS_MARK[t.status] ?? '[ ]'} ${t.subject}`) : todos;
  return { ...(plan?.text !== undefined ? { planText: plan.text } : {}), ...(plan?.path !== undefined ? { planPath: plan.path } : {}), tasks: lines };
}

